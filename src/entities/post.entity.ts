import { PostStateEnum } from "@common/@types";
import { BaseEntity } from "@common/database";
import {
  Entity,
  ManyToMany,
  ManyToOne,
  OneToMany,
  Property,
  BeforeCreate,
  BeforeUpdate,
  BeforeUpsert,
  Check,
  Enum,
  Index,
} from "@mikro-orm/decorators/legacy";
import type { EventArgs } from "@mikro-orm/postgresql";
import type { Rel } from "@mikro-orm/postgresql";
import { Opt, Ref } from "@mikro-orm/postgresql";
import { Collection } from "@mikro-orm/postgresql";
import { slugify } from "helper-fns";

import { User } from "./index";
import { Category, Comment, Tag } from "./index";

@Entity()
@Index({ name: "post_search_vector_index", properties: ["searchVector"], type: "gin" })
export class Post extends BaseEntity {
  @Property({ index: true })
  slug?: string;

  @Property({ index: true })
  title!: string;

  @Property({ type: "text" })
  description!: string;

  @Property({ type: "text" })
  content!: string;

  @Property()
  @Check({ expression: "reading_time >= 0" })
  readingTime: number & Opt = 0;

  @Property()
  readCount: number & Opt = 0;

  @Property({ index: true })
  published: boolean & Opt = false;

  // Enforced in the database because the application-level guard in
  // `PostService.unFavorite` cannot stop a concurrent write from going negative.
  @Property()
  @Check({ expression: "favorites_count >= 0" })
  favoritesCount: number & Opt = 0;

  // Guards the read-modify-write of `favoritesCount`: a concurrent change makes
  // the flush match zero rows and throw `OptimisticLockError`.
  @Property({ version: true })
  version: number & Opt = 1;

  @ManyToOne({
    index: true,
  })
  author!: Rel<Ref<User>>;

  @OneToMany(() => Comment, (comment) => comment.post, {
    orphanRemoval: true,
  })
  comments = new Collection<Comment>(this);

  @ManyToMany(() => Tag, "posts", { owner: true })
  tags = new Collection<Tag>(this);

  @ManyToMany(() => Category, "posts", { owner: true })
  categories = new Collection<Category>(this);

  // Title outranks description, which outranks content. Generated by Postgres, so never written.
  @Property({
    columnType: "tsvector",
    generated: `(setweight(to_tsvector('english', coalesce(title, '')), 'A') || setweight(to_tsvector('english', coalesce(description, '')), 'B') || setweight(to_tsvector('english', coalesce(content, '')), 'C')) stored`,
    hidden: true,
    lazy: true,
    nullable: true,
  })
  searchVector?: string;

  @Enum({ items: () => PostStateEnum })
  state: PostStateEnum & Opt = PostStateEnum.DRAFT;

  constructor(partial?: Partial<Post>) {
    super();
    Object.assign(this, partial);
  }

  @BeforeUpsert()
  @BeforeCreate()
  @BeforeUpdate()
  async generateSlug(eventArguments: EventArgs<this>) {
    if (eventArguments.changeSet?.payload?.title) {
      this.slug = `${slugify(this.title)}-${Math.trunc(Math.random() * 36 ** 6).toString(36)}`;
    }
    this.readingTime = this.getReadingTime(this.content);
  }

  getReadingTime(content: string) {
    const avgWordsPerMin = 250;
    const count = content.match(/\w+/g)?.length ?? 0;

    return Math.ceil(count / avgWordsPerMin);
  }
}
